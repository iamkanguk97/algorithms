# 두번째 묶음의 첫번째 원소 -> 두번째 줄의 뒤에서 첫번째 원소 (F)
# 두번째 묶음의 두번째 원소 -> 세번째 줄의 뒤에서 두번째 원소 (G)
# 두번째 묶음의 세번째 원소 -> 네번째 줄의 뒤에서 세번째 원소 (H)
# 두번째 묶음의 네번째 원소 -> 다벗번째 줄의 뒤에서 네번째 원소 (I)

# 세번째 묶음의 첫번째 원소 -> 세번째 줄의 뒤에서 첫번째 원소 (J)
# 세번째 묶음의 두번째 원소 -> 세번째 줄의 뒤에서 두번째 원소 (K)
# 세번째 묶음의 세번째 원소 -> 세번째 줄의 뒤에서 세번째 원소 (L)

# 네번째 묶음의 첫번째 원소 -> 네번째 줄의 뒤에서 첫번째 원소 (M)
# 네번째 묶음의 두번째 원소 -> 네번째 줄의 뒤에서 두번째 원소 (N)

# 다섯번째 묶음의 첫번째 원소 -> 다섯번째 줄의 뒤에서 첫번째 원소 (O)

n = int(input())
arr = [[' '] * n for _ in range(n)]
ch = 'A'

for i in range(n): # 묶음
    for j in range(n - i): # 순서
        arr[i+j][n-1-j] = ch
        ch = chr(ord('A') + (ord(ch) - ord('A') + 1) % 26)

for i in range(n):
    for j in range(n):
        print(arr[i][j], end=' ')
    print()